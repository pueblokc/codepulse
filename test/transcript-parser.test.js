'use strict';
// Pin a non-UTC zone so local-date bucketing is actually exercised.
process.env.TZ = 'America/Denver';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const { parseTranscriptContent, normaliseUsage, TranscriptStore } = require('../lib/transcript-parser');
const { makeClaudeDir, assistant, user } = require('./helpers');

const jsonl = (entries) => entries.map(e => typeof e === 'string' ? e : JSON.stringify(e)).join('\n');

test('usage is counted once per message even though each content block is its own line', () => {
  const usage = { input_tokens: 100, output_tokens: 50, cache_read_input_tokens: 1000, cache_creation_input_tokens: 200 };
  const { meta, usage: u } = parseTranscriptContent(jsonl([
    user('fix the bug', '2026-10-20T10:00:00Z'),
    assistant({ id: 'msg_1', ts: '2026-10-20T10:00:05Z', usage, content: [{ type: 'thinking', thinking: '' }] }),
    assistant({ id: 'msg_1', ts: '2026-10-20T10:00:06Z', usage, content: [{ type: 'text', text: 'Looking' }] }),
    assistant({ id: 'msg_1', ts: '2026-10-20T10:00:07Z', usage, content: [{ type: 'tool_use', id: 'tu_1', name: 'Read', input: {} }] }),
  ]));
  assert.equal(u.size, 1);
  const rec = [...u.values()][0];
  assert.equal(rec.input, 100);
  assert.equal(rec.output, 50);
  assert.equal(rec.cache_read, 1000);
  assert.equal(rec.cache_write_5m, 200);
  assert.equal(meta.assistant_messages, 1);
  assert.equal(meta.tool_calls, 1);
});

test('streaming duplicates keep the largest counters', () => {
  const { usage } = parseTranscriptContent(jsonl([
    assistant({ id: 'm', ts: '2026-10-20T10:00:00Z', usage: { input_tokens: 10, output_tokens: 1 } }),
    assistant({ id: 'm', ts: '2026-10-20T10:00:01Z', usage: { input_tokens: 10, output_tokens: 400 } }),
  ]));
  assert.equal([...usage.values()][0].output, 400);
});

test('tool results, meta entries and slash-command wrappers are not user messages', () => {
  const { meta } = parseTranscriptContent(jsonl([
    user('Caveat: The messages below were generated by the user while running local commands.', '2026-10-20T09:59:00Z', { isMeta: true }),
    user('<command-name>/clear</command-name>', '2026-10-20T09:59:30Z'),
    user('Refactor the parser', '2026-10-20T10:00:00Z'),
    { type: 'user', timestamp: '2026-10-20T10:00:10Z', message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'x', content: 'file body' }] } },
    { type: 'user', timestamp: '2026-10-20T10:01:00Z', message: { role: 'user', content: [{ type: 'text', text: 'and add tests' }] } },
  ]));
  assert.equal(meta.user_messages, 2);
  assert.equal(meta.description, 'Refactor the parser');
});

test('summary entries become the title; bad lines and synthetic models are skipped', () => {
  const { meta, usage } = parseTranscriptContent(jsonl([
    { type: 'summary', summary: 'Parser refactor', leafUuid: 'x' },
    '{not json',
    assistant({ id: 's', model: '<synthetic>', ts: '2026-10-20T10:00:00Z', usage: { input_tokens: 0, output_tokens: 0 } }),
    { type: 'file-history-snapshot', snapshot: {} },
  ]));
  assert.equal(meta.title, 'Parser refactor');
  assert.equal(meta.parse_errors, 1);
  assert.equal(usage.size, 0);
  assert.equal(meta.models.size, 0);
});

test('invalid timestamps are ignored instead of poisoning duration', () => {
  const { meta } = parseTranscriptContent(jsonl([
    user('a', 'not-a-date'),
    user('b', '2026-10-20T10:00:00Z'),
    user('c', '2026-10-20T10:30:00Z'),
  ]));
  assert.equal(meta.lastTs - meta.firstTs, 30 * 60000);
});

test('normaliseUsage splits 1h cache writes from 5m writes', () => {
  const u = normaliseUsage({
    input_tokens: 5, output_tokens: 6, cache_read_input_tokens: 7, cache_creation_input_tokens: 300,
    cache_creation: { ephemeral_5m_input_tokens: 100, ephemeral_1h_input_tokens: 200 },
  });
  assert.deepEqual(u, { input: 5, output: 6, cache_read: 7, cache_write_5m: 100, cache_write_1h: 200 });
  assert.deepEqual(normaliseUsage(null), { input: 0, output: 0, cache_read: 0, cache_write_5m: 0, cache_write_1h: 0 });
});

test('TranscriptStore finds current, legacy and sub-agent transcripts', (t) => {
  const dir = makeClaudeDir();
  t.after(() => dir.cleanup());
  const now = Date.parse('2026-10-20T12:00:00Z');

  dir.write('-home-me-app/aaa.jsonl', [
    user('hello', '2026-10-20T10:00:00Z', { cwd: '/home/me/app' }),
    assistant({ id: 'a1', model: 'claude-opus-4-6', ts: '2026-10-20T10:00:05Z', usage: { input_tokens: 1e6, output_tokens: 0 } }),
  ], now - 5 * 60000);
  dir.write('-home-me-app/aaa/subagents/agent-1.jsonl', [
    assistant({ id: 'sub1', model: 'claude-haiku-4-5-20251001', ts: '2026-10-20T10:01:00Z', usage: { input_tokens: 1e6, output_tokens: 0 } }),
  ], now - 5 * 60000);
  dir.write('-home-me-old/sessions/bbb.jsonl', [
    user('legacy layout', '2026-10-19T10:00:00Z'),
  ], now - 3 * 86400000);

  const store = new TranscriptStore();
  const { sessions } = store.readAll(dir.projects, { now, activeThresholdMinutes: 10 });
  assert.equal(sessions.length, 2);

  const a = sessions.find(s => s.session_id === 'aaa');
  assert.equal(a.status, 'active');
  assert.equal(a.subagent_files, 1);
  assert.equal(a.cwd, '/home/me/app');
  assert.equal(a.tokens.input, 2e6);
  // $5 (Opus 4.6 input) + $1 (Haiku 4.5 input)
  assert.ok(Math.abs(a.cost_usd - 6) < 1e-9, String(a.cost_usd));
  assert.equal(a.primary_model, 'claude-opus-4-6');
  assert.equal(a.primary_model_label, 'Opus 4.6');

  const b = sessions.find(s => s.session_id === 'bbb');
  assert.equal(b.status, 'stale');
  assert.equal(b.description, 'legacy layout');
});

test('activeThresholdMinutes setting controls the active status', (t) => {
  const dir = makeClaudeDir();
  t.after(() => dir.cleanup());
  const now = Date.parse('2026-10-20T12:00:00Z');
  dir.write('p/s.jsonl', [user('x', '2026-10-20T11:40:00Z')], now - 20 * 60000);
  const store = new TranscriptStore();
  assert.equal(store.readAll(dir.projects, { now, activeThresholdMinutes: 10 }).sessions[0].status, 'recent');
  assert.equal(store.readAll(dir.projects, { now, activeThresholdMinutes: 30 }).sessions[0].status, 'active');
});

test('daily totals de-duplicate history copied into a resumed session', (t) => {
  const dir = makeClaudeDir();
  t.after(() => dir.cleanup());
  const shared = assistant({ id: 'm1', model: 'claude-sonnet-4-6', ts: '2026-10-20T10:00:00Z', usage: { input_tokens: 1000, output_tokens: 10 } });
  dir.write('p/first.jsonl', [shared]);
  dir.write('p/resumed.jsonl', [shared,
    assistant({ id: 'm2', model: 'claude-sonnet-4-6', ts: '2026-10-21T10:00:00Z', usage: { input_tokens: 500, output_tokens: 5 } })]);
  const { daily, sessions } = new TranscriptStore().readAll(dir.projects);
  assert.equal(sessions.length, 2);
  assert.equal(daily['2026-10-20']['claude-sonnet-4-6'].input, 1000);
  assert.equal(daily['2026-10-21']['claude-sonnet-4-6'].input, 500);
});

test('TranscriptStore reuses parse results for unchanged files and drops deleted ones', (t) => {
  const dir = makeClaudeDir();
  t.after(() => dir.cleanup());
  const f = dir.write('p/s.jsonl', [user('x', '2026-10-20T10:00:00Z')]);
  const store = new TranscriptStore();
  store.readAll(dir.projects);
  const cached = store.cache.get(f);
  store.readAll(dir.projects);
  assert.equal(store.cache.get(f), cached);
  fs.appendFileSync(f, JSON.stringify(user('y', '2026-10-20T10:05:00Z')) + '\n');
  const { sessions } = store.readAll(dir.projects);
  assert.equal(sessions[0].user_messages, 2);
  fs.rmSync(f);
  store.readAll(dir.projects);
  assert.equal(store.cache.size, 0);
});

test('missing projects dir yields no sessions', () => {
  const { sessions, daily } = new TranscriptStore().readAll(path.join(__dirname, 'does-not-exist'));
  assert.deepEqual(sessions, []);
  assert.deepEqual(daily, {});
});
